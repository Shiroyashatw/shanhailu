def entry(b, x, y, w, nm, pg, rw='', done=False, dim=False, h=34):
    b.box(x, y, w, h, 'sel' if done else ('off' if dim else 'p'))
    if done:
        b.box(x + 3, y + 5, 24, 24, 'dk'); b.t(x + 3, y + 9, 24, '✓', 'f10b', 'c wh')
    else:
        b.box(x + 3, y + 5, 24, 24, 'p'); b.t(x + 3, y + 9, 24, nm[0], 'f10b', 'c')
    b.t(x + 32, y + 2, w - 36, nm, 'f10b' if done else 'f10', 'off' if dim else '')
    b.t(x + 32, y + 17, w - 36, pg, 'f9', 'dim')

