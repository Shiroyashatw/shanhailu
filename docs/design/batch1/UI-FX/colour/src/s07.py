def row_box(s, x, y, w, h, cells, bold=False, hdr=False):
    s.box(x, y, w, h, 'in' if hdr else 'p')
    cx = x
    for (cw_, txt) in cells:
        s.t(cx + 6, y + (h - 14) // 2 if h <= 36 else y + 4, cw_ - 10, txt, 'f10b' if (bold or hdr) else 'f10', 'ml' if h > 36 else '', h=(h - 6) if h > 36 else None)
        cx += cw_

