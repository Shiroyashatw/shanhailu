def mini_map(b, x, y, w, h, marker, stop=False, arrive=False, bar=None):
    b.box(x, y, w, h, 'map')
    pts = [(x + 30, y + h // 2), (x + w // 2, y + h // 2), (x + w - 34, y + h // 2)]
    b.line(pts[0][0], pts[0][1], pts[1][0], pts[1][1], kind='selr')
    b.line(pts[1][0], pts[1][1], pts[2][0], pts[2][1], kind='selr')
    for i, (px, py) in enumerate(pts):
        b.box(px - 11, py - 11, 22, 22, 'sel' if i == 2 else 'p')
        b.t(px - 10, py - 7, 20, '鎮徑林'[i], 'f10b', 'c')
    if arrive:
        b.box(pts[2][0] - 16, pts[2][1] - 16, 32, 32, 'glow', layer=1)
    mx = int(pts[0][0] + (pts[2][0] - pts[0][0]) * marker)
    b.box(mx - 6, pts[0][1] - 6, 12, 12, 'mk', layer=1)
    if stop:
        b.box(mx - 7, pts[0][1] - 32, 14, 16, 'rd', layer=2); b.t(mx - 7, pts[0][1] - 31, 14, '!', 'f10b', 'c red', layer=2)

