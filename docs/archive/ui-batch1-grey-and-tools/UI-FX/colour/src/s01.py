def mini_scene(b, x, y, w, h, a, phase, mark, label):
    b.box(x, y, w, h, 'art')
    for i, (nm, rx, ry) in enumerate([('客棧', 14, 10), ('鎮衙', 110, 8), ('藥鋪', 210, 14)]):
        b.box(x + rx, y + ry, 60, 30, 'ghost')
        b.box(x + rx + 4, y + ry + 34, 52, 15, 'chip'); b.t(x + rx + 5, y + ry + 35, 50, nm, 'f9', 'c')
    b.box(x + 130, y + 56, 6, 6, 'dk round')
    if a:
        tint(b, x, y, w, h, a, layer=1)

